#!/bin/bash
# Which Sony binary touches which kernel node, device, property or file. Strings only, so it lists
# what a binary names, not what it does with it.
# usage: tools/re_touchpoints.sh [rootfs/vendor/sony]   > analysis/FIRMWARE_touchpoints.md
R=${1:-artifacts/rootfs_mnt/vendor/sony}
echo "# Touch points: the paths and properties each Sony binary names"
echo
echo "Generated by \`tools/re_touchpoints.sh $R\`. Strings only: a name here means the binary"
echo "contains it, not that the path is used on this model. Index: [\`FIRMWARE_MAP.md\`](FIRMWARE_MAP.md)."
for f in "$R"/lib/*.so "$R"/bin/*; do
    case "$f" in *Qt5*|*icu*|*libcrypto*|*libssl*|*libcurl*|*harfbuzz*|*.sh|*.json|*.appcfg) continue ;; esac
    t=$(strings -n 6 "$f" | grep -E '^(/sys/|/proc/|/dev/|/data/|/tmp/|/contents|/system/|/var/|/emmc|(persist|ro|sys|init\.svc)\.[a-z0-9_.]+$|hw:[0-9])' | grep -v '\.so$\|/lib:\|\$ORIGIN' | sort -u)
    [ -z "$t" ] && continue
    echo; echo "## $(basename "$f")"; echo
    echo "$t" | sed 's/^/* `/; s/$/`/'
done
