#!/usr/bin/env python3
"""Build Cinder's embedded translations from player/cinder-ui/locales/. Standard library only.

    python3 tools/generate_locales.py              write player/cinder-ui/src/i18n_catalog.rs
    python3 tools/generate_locales.py --check      fail if that file is stale (CI runs this)
    python3 tools/generate_locales.py --status     how complete each language is
    python3 tools/generate_locales.py --status de  ...and every string German still lacks
    python3 tools/generate_locales.py --new de     start locales/de.json with every string, blank

docs/LOCALIZATION.md is the guide. English is the source: the keys of every locale file are the
English UI strings, and a blank or missing translation shows the English one.
"""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCALES = ROOT / "player/cinder-ui/locales"
CATALOG = ROOT / "player/cinder-ui/src/i18n_catalog.rs"
COMPONENTS = ROOT / "cinder-home/deploy/components.conf"
SOURCES = [ROOT / "player/cinder-ui/src", ROOT / "player/cinder-ffi/src"]
PLACEHOLDER = re.compile(r"(?<!\{)\{[^{}]*\}(?!\})")
STRING = r'"((?:[^"\\]|\\.)*)"'
# The calls whose first literal is a catalog key; text_with_key's key is its SECOND literal.
CALLS = [
    re.compile(r"i18n::text\(\s*" + STRING),
    re.compile(r"ui_format!\(\s*" + STRING),
    re.compile(r"notify_format\(\s*" + STRING),
    re.compile(r"format_template\(\s*" + STRING),
    re.compile(r"text_with_key\(\s*" + STRING + r"\s*,\s*" + STRING),
]


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def component_var(tag):
    """The installer checkbox for a language: CINDER_LANG_ZH_CN for zh-CN."""
    return "CINDER_LANG_" + tag.upper().replace("-", "_")


def languages():
    langs = json.loads((LOCALES / "languages.json").read_text(encoding="utf8"))
    if not langs or langs[0]["tag"] != "en":
        raise SystemExit("languages.json: English (en) must be the first entry")
    for lang in langs:
        for field in ("tag", "id", "name", "english", "word"):
            if not isinstance(lang.get(field), str) or not lang[field]:
                raise SystemExit(f"languages.json: {lang.get('tag', '?')} needs a {field!r}")
        if not re.fullmatch(r"[A-Z][A-Za-z]*", lang["id"]):
            raise SystemExit(f"languages.json: id {lang['id']!r} must be a CamelCase word")
        if not re.fullmatch(r"[a-z]{2,3}(-[A-Za-z0-9]{2,8})*", lang["tag"]):
            raise SystemExit(f"languages.json: {lang['tag']!r} is not a BCP 47 tag like de or pt-BR")
    files = {p.stem for p in LOCALES.glob("*.json")} - {"languages"}
    tags = {lang["tag"] for lang in langs[1:]}
    if files != tags:
        raise SystemExit(
            "every locales/<tag>.json needs an entry in languages.json and the other way round: "
            f"files {sorted(files)}, entries {sorted(tags)}"
        )
    return langs


def translations(tag):
    """English -> translation, without the blanks (a blank is an untranslated string)."""
    pairs = json.loads((LOCALES / f"{tag}.json").read_text(encoding="utf8"))
    for english, value in pairs.items():
        if not isinstance(value, str):
            raise SystemExit(f"{tag}.json: the translation of {english!r} must be a string")
    return {k: v for k, v in pairs.items() if v}


def unescape(literal):
    return re.sub(
        r"\\(u\{([0-9a-fA-F]+)\}|.)",
        lambda m: chr(int(m.group(2), 16)) if m.group(2) else {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)),
        literal,
    )


def source_keys():
    """English strings the code passes to a translation call directly. Labels that reach the
    catalog through a constant or a table are not seen here; the locale files carry those."""
    keys = set()
    for folder in SOURCES:
        for path in folder.glob("*.rs"):
            if path in (CATALOG, CATALOG.with_name("i18n.rs")):  # i18n.rs: its tests' made-up keys
                continue
            text = path.read_text(encoding="utf8")
            for call in CALLS:
                for m in call.finditer(text):
                    keys.add(unescape(m.groups()[-1]))
    return keys


def all_keys(langs):
    keys = source_keys()
    for lang in langs[1:]:
        keys |= set(json.loads((LOCALES / f"{lang['tag']}.json").read_text(encoding="utf8")))
    return keys


def generate(langs):
    per = {lang["id"]: translations(lang["tag"]) for lang in langs[1:]}
    ids = [lang["id"] for lang in langs]
    out = [
        "// Generated by tools/generate_locales.py from player/cinder-ui/locales/. Do not edit:\n"
        "// change the JSON and run the tool (docs/LOCALIZATION.md).\n\n"
        "/// A UI language. The first one is the source every other is translated from.\n"
        "#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]\npub enum Language {\n"
        "    #[default]\n",
    ]
    out += [f"    {i},\n" for i in ids]
    out.append("}\n\n#[rustfmt::skip]\nimpl Language {\n")
    out.append(f"    pub const ALL: [Language; {len(ids)}] = [{', '.join('Language::' + i for i in ids)}];\n")
    for field, doc in [
        ("tag", "The BCP 47 tag that is saved and that the installer passes on."),
        ("name", "The language's name in itself, as its own speakers read it."),
        ("english", "The language's name in English."),
        ("word", "The word for \\\"language\\\" in this language, for the Settings row."),
    ]:
        out.append(f'    #[doc = "{doc}"]\n    pub fn {field}(self) -> &\'static str {{\n        match self {{\n')
        out += [f"            Language::{lang['id']} => {quote(lang[field])},\n" for lang in langs]
        out.append("        }\n    }\n")
    out.append("    /// Its UI copy draws from the bundled CJK subset (assets/fonts/CinderHansUI).\n")
    out.append("    pub fn uses_cjk_ui_font(self) -> bool {\n        matches!(self, ")
    out.append(" | ".join(f"Language::{l['id']}" for l in langs if l.get("cjk_font")) or "Language::English if false")
    out.append(")\n    }\n}\n\n#[rustfmt::skip]\n")
    out.append("pub(super) fn lookup(language: Language, source: &str) -> Option<&'static str> {\n")
    out.append("    match language {\n        Language::English => None,\n")
    out += [f"        Language::{i} => {i.lower()}(source),\n" for i in ids[1:]]
    out.append("    }\n}\n")
    for i in ids[1:]:
        out.append(f"\n#[rustfmt::skip]\nfn {i.lower()}(source: &str) -> Option<&'static str> {{\n    match source {{\n")
        out += [f"        {quote(k)} => Some({quote(v)}),\n" for k, v in sorted(per[i].items())]
        out.append("        _ => None,\n    }\n}\n")

    out.append(
        "\n/// Format a UI template in the current language; the arguments are checked by Rust for\n"
        "/// every language, because each arm is its own `format!`.\n#[macro_export]\nmacro_rules! ui_format {\n"
    )
    fields = lambda value: sorted(PLACEHOLDER.findall(value))
    for english in sorted(set().union(*per.values()) if per else ()):
        if not PLACEHOLDER.search(english):
            continue
        arms = []
        for i in ids[1:]:
            t = per[i].get(english)
            if t is None or t == english:
                continue
            if fields(english) != fields(t):
                raise SystemExit(f"{i}: the placeholders in the translation of {english!r} differ from English")
            arms.append(f"            $crate::i18n::Language::{i} => format!({quote(t)} $(, $($args)*)?),\n")
        if arms:
            out.append(f"    ({quote(english)} $(, $($args:tt)*)?) => {{\n        match $crate::i18n::current() {{\n")
            out += arms
            out.append(f"            _ => format!({quote(english)} $(, $($args)*)?),\n        }}\n    }};\n")
    out.append("    ($fmt:literal $(, $($args:tt)*)?) => { format!($fmt $(, $($args)*)?) };\n}\n")
    return "".join(out)


def check_installer(langs):
    conf = COMPONENTS.read_text(encoding="utf8")
    for lang in langs:
        var = component_var(lang["tag"])
        if not re.search(rf"^\S+\s*\|\s*{var}\s*\|\s*bool\s*\|", conf, re.M):
            raise SystemExit(f"{COMPONENTS.name} needs a bool entry {var} for {lang['english']}")


def status(langs, tag):
    keys = all_keys(langs)
    for lang in langs[1:]:
        done = translations(lang["tag"])
        print(f"{lang['tag']:8} {lang['english']:24} {len(keys & set(done))} of {len(keys)} translated")
        if tag == lang["tag"]:
            for k in sorted(keys - set(done)):
                print("    " + quote(k))


def new(langs, tag):
    path = LOCALES / f"{tag}.json"
    if path.exists():
        raise SystemExit(f"{path.relative_to(ROOT)} already exists")
    path.write_text(json.dumps({k: "" for k in sorted(all_keys(langs))}, ensure_ascii=False, indent=2) + "\n", encoding="utf8")
    print(f"wrote {path.relative_to(ROOT)}: fill in the blanks. Then add {tag} to languages.json, add")
    print(f"the {component_var(tag)} checkbox to {COMPONENTS.relative_to(ROOT)}, and run this tool.")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--status", nargs="?", const="", metavar="TAG")
    parser.add_argument("--new", metavar="TAG")
    args = parser.parse_args()

    if args.new:
        return new(languages(), args.new)
    langs = languages()
    if args.status is not None:
        return status(langs, args.status)
    check_installer(langs)
    body = generate(langs)
    if args.check:
        if not CATALOG.exists() or CATALOG.read_text(encoding="utf8") != body:
            raise SystemExit("i18n_catalog.rs is stale: run python3 tools/generate_locales.py")
    else:
        CATALOG.write_text(body, encoding="utf8", newline="\n")


if __name__ == "__main__":
    main()
